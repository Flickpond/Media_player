import base64
from datetime import UTC, datetime, timedelta
from functools import lru_cache
from typing import Protocol
from urllib.parse import quote

from botocore.signers import CloudFrontSigner
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import padding
from minio import Minio
from starlette.concurrency import run_in_threadpool

from app.config import get_settings
from app.services.minio_client import bucket, public_client


class OutputUrlSigner(Protocol):
    async def create_url(self, output_key: str) -> str: ...

    async def create_inline_url(self, output_key: str) -> str: ...


class MinioOutputUrlSigner:
    def __init__(
        self,
        client: Minio,
        *,
        bucket: str,
        expiry_seconds: int,
    ) -> None:
        self._client = client
        self._bucket = bucket
        self._expiry = timedelta(seconds=expiry_seconds)

    async def create_url(self, output_key: str) -> str:
        # Ask the object store to serve the object as a download rather than
        # rendering it inline. Uploads are already restricted to video types,
        # so this is the second layer: if something non-video ever reaches a
        # bucket, opening its URL saves a file instead of executing it on the
        # object store's origin. A <video> element ignores the header, so the
        # player still plays the result.
        return await run_in_threadpool(
            self._client.presigned_get_object,
            self._bucket,
            output_key,
            expires=self._expiry,
            response_headers={"response-content-disposition": "attachment"},
        )

    async def create_inline_url(self, output_key: str) -> str:
        """The same signature without the forced download.

        For HLS parts, which hls.js fetches with XHR and feeds to the media
        source rather than navigating to. `Content-Disposition: attachment`
        has no effect on an XHR, so this is not a behaviour change so much
        as removing a header that would only ever confuse whoever debugs
        this next.

        Deliberately a second method rather than a parameter on the first:
        the download path's forced disposition is a control worth being
        hard to switch off by accident, and the MP4 must keep it.
        """
        return await run_in_threadpool(
            self._client.presigned_get_object,
            self._bucket,
            output_key,
            expires=self._expiry,
        )


class CloudFrontOutputUrlSigner:
    """HLS segments through CloudFront; the MP4 and thumbnails as before.

    Segments are what a viewer streams -- hundreds per video, fetched again
    by every viewer -- so they are the traffic worth serving from a CDN:
    cached near the viewer, and inside CloudFront's free monthly allowance.
    Each URL is a CloudFront signed URL (canned policy, expiring like the
    storage URLs did), issued by the HLS route after its ownership check, so
    a segment is exactly as private as before. CloudFront leaves the
    signature out of its cache key, so one cached copy serves every viewer.

    `create_url` is not routed through the CDN on purpose: the MP4 and the
    thumbnail keep the storage URL with its forced `attachment` disposition,
    a control worth more than the CDN on a once-per-video download.
    """

    def __init__(
        self,
        storage: OutputUrlSigner,
        *,
        domain: str,
        key_pair_id: str,
        private_key_pem: bytes,
        expiry_seconds: int,
        now=lambda: datetime.now(UTC),
    ) -> None:
        self._storage = storage
        self._base = f"https://{domain.strip().rstrip('/')}"
        key = serialization.load_pem_private_key(private_key_pem, password=None)
        # RSA-SHA1 is CloudFront's requirement for canned-policy signed URLs,
        # not a choice. SHA-1's weakness is collisions; forging an RSA
        # signature over a policy still needs the private key, which lives
        # only in SSM and this process. Hence the suppression (Sonar S4790).
        self._signer = CloudFrontSigner(
            key_pair_id,
            lambda message: key.sign(message, padding.PKCS1v15(), hashes.SHA1()),  # NOSONAR
        )
        self._expiry = timedelta(seconds=expiry_seconds)
        self._now = now

    async def create_url(self, output_key: str) -> str:
        return await self._storage.create_url(output_key)

    async def create_inline_url(self, output_key: str) -> str:
        # The key is RSA-2048, generated by infra/terraform; it never leaves
        # SSM and the API's memory.
        url = f"{self._base}/{quote(output_key)}"
        return self._signer.generate_presigned_url(url, date_less_than=self._now() + self._expiry)


@lru_cache
def get_output_url_signer() -> OutputUrlSigner:
    # The *public* client, deliberately not the internal one: the host it is
    # built with lands inside the SigV4 signature, and the URL is opened by a
    # browser. Swapping this for internal_client() breaks playback silently.
    settings = get_settings()
    storage = MinioOutputUrlSigner(
        public_client(),
        bucket=bucket(),
        expiry_seconds=settings.output_url_expiry_seconds,
    )
    if not settings.cloudfront_domain:
        return storage
    # All three or none: a domain without a key would sign nothing a
    # browser could open, and failing at startup says so at once.
    if not (settings.cloudfront_key_pair_id and settings.cloudfront_private_key_b64):
        raise RuntimeError("CLOUDFRONT_DOMAIN is set without its key pair id and private key")
    return CloudFrontOutputUrlSigner(
        storage,
        domain=settings.cloudfront_domain,
        key_pair_id=settings.cloudfront_key_pair_id,
        private_key_pem=base64.b64decode(settings.cloudfront_private_key_b64),
        expiry_seconds=settings.output_url_expiry_seconds,
    )
